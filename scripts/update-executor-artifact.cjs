const fs = require("node:fs");
const path = require("node:path");
const { keccak256Hex } = require("../dist/adapters/keccak.js");

const artifactPath = path.resolve("out/ScopedRecoveryExecutor.sol/ScopedRecoveryExecutor.json");
const outputPath = path.resolve("src/application/executor-artifact.ts");
const artifact = JSON.parse(fs.readFileSync(artifactPath, "utf8"));
const creationBytecode = artifact.bytecode?.object;
const runtimeBytecode = artifact.deployedBytecode?.object;
const immutableReferences = artifact.deployedBytecode?.immutableReferences ?? {};

if (typeof creationBytecode !== "string" || !/^0x(?:[0-9a-fA-F]{2})+$/.test(creationBytecode)) {
  throw new Error("Foundry did not produce valid executor creation bytecode.");
}
if (typeof runtimeBytecode !== "string" || !/^0x(?:[0-9a-fA-F]{2})+$/.test(runtimeBytecode)) {
  throw new Error("Foundry did not produce valid executor runtime bytecode.");
}
if (Object.keys(artifact.bytecode.linkReferences ?? {}).length !== 0) {
  throw new Error("Executor artifact unexpectedly requires external library linking.");
}

const immutableRanges = Object.values(immutableReferences).flat()
  .map(({ start, length }) => ({ start, length }))
  .sort((a, b) => a.start - b.start);
const runtime = Buffer.from(runtimeBytecode.slice(2), "hex");
for (const range of immutableRanges) {
  if (!Number.isInteger(range.start) || !Number.isInteger(range.length) ||
      range.start < 0 || range.length <= 0 || range.start + range.length > runtime.length) {
    throw new Error("Foundry emitted an invalid immutable reference range.");
  }
  runtime.fill(0, range.start, range.start + range.length);
}
const normalizedRuntimeCodeHash = keccak256Hex("0x" + runtime.toString("hex"));
const sourceCommit = process.env.GITHUB_SHA;
if (!/^[0-9a-f]{40}$/i.test(sourceCommit ?? "")) {
  throw new Error("GITHUB_SHA is required to pin the executor build source.");
}
const content = [
  "// Generated by scripts/update-executor-artifact.cjs; do not edit by hand.",
  "// Foundry compiler and optimizer settings are pinned in foundry.toml.",
  "export const EXECUTOR_CREATION_BYTECODE = " + JSON.stringify(creationBytecode) + ";",
  "export const EXECUTOR_NORMALIZED_RUNTIME_CODE_HASH = " + JSON.stringify(normalizedRuntimeCodeHash) + ";",
  "export const EXECUTOR_IMMUTABLE_RANGES = " + JSON.stringify(immutableRanges) + " as const;",
  "export const EXECUTOR_BUILD_SOURCE_COMMIT = " + JSON.stringify(sourceCommit) + ";",
  ""
].join("\n");
fs.writeFileSync(outputPath, content);
console.log("Pinned executor artifact", {
  sourceCommit, creationBytes: (creationBytecode.length - 2) / 2,
  runtimeBytes: runtime.length, normalizedRuntimeCodeHash, immutableRanges
});
